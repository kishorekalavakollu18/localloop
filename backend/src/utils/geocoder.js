/**
 * Extract 6-digit Indian PIN code from text
 */
function extractPincode(text) {
  if (!text || typeof text !== 'string') return null;
  const match = text.match(/\b[1-9][0-9]{5}\b/);
  return match ? match[0] : null;
}

/**
 * Geocode an address and/or PIN code into [lng, lat] coordinates
 */
async function geocodeAddress(address, pincode) {
  // 1. Try provided pincode or extract from address
  const pin = pincode ? pincode.toString().trim() : extractPincode(address);

  if (pin && INDIAN_PINCODE_COORDINATES[pin]) {
    const info = INDIAN_PINCODE_COORDINATES[pin];
    return {
      coordinates: [info.lng, info.lat],
      pincode: pin,
      formattedAddress: address || `${info.name}, ${info.city} - ${pin}`,
      source: 'pincode_cache',
    };
  }

  // 2. Online Geocoding via Nominatim with full address query
  const cleanAddress = address && address !== pin ? address : '';
  const query = [cleanAddress, pin, 'India'].filter(Boolean).join(', ');
  if (query.length > 3) {
    try {
      const url = `https://nominatim.openstreetmap.org/search?q=${encodeURIComponent(query)}&format=json&limit=1`;
      const response = await fetch(url, {
        headers: { 'User-Agent': 'LocalLoop-Hyperlocal-App/1.0' },
      });
      if (response.ok) {
        const results = await response.json();
        if (results && results.length > 0) {
          const lat = parseFloat(results[0].lat);
          const lon = parseFloat(results[0].lon);
          return {
            coordinates: [lon, lat],
            pincode: pin || '',
            formattedAddress: results[0].display_name || address,
            source: 'nominatim',
          };
        }
      }
    } catch (err) {
      console.warn('Online geocoding fetch error:', err.message);
    }
  }

  // 2b. If full address wasn't resolved by Nominatim, search specifically for the 6-digit PIN code!
  if (pin && /^[1-9][0-9]{5}$/.test(pin)) {
    try {
      const pinUrl = `https://nominatim.openstreetmap.org/search?q=${encodeURIComponent(pin + ', India')}&format=json&limit=1`;
      const response = await fetch(pinUrl, {
        headers: { 'User-Agent': 'LocalLoop-Hyperlocal-App/1.0' },
      });
      if (response.ok) {
        const results = await response.json();
        if (results && results.length > 0) {
          const lat = parseFloat(results[0].lat);
          const lon = parseFloat(results[0].lon);
          return {
            coordinates: [lon, lat],
            pincode: pin,
            formattedAddress: address || results[0].display_name,
            source: 'nominatim_pincode',
          };
        }
      }
    } catch (err) {
      console.warn('Nominatim PIN geocoding fetch error:', err.message);
    }
  }

  // 3. Regional Zone Heuristics based on first 2 digits of Indian PIN code
  if (pin) {
    if (pin.startsWith('52') || pin.startsWith('53')) {
      // Coastal Andhra (Guntur / Vijayawada corridor)
      return {
        coordinates: [80.4365, 16.3067],
        pincode: pin,
        formattedAddress: address || `Andhra Pradesh Area (${pin})`,
        source: 'zone_ap',
      };
    }
    if (pin.startsWith('51')) {
      // Rayalaseema AP (Tirupati / Kurnool corridor)
      return {
        coordinates: [79.4192, 13.6288],
        pincode: pin,
        formattedAddress: address || `Rayalaseema AP (${pin})`,
        source: 'zone_ap_south',
      };
    }
    if (pin.startsWith('50')) {
      // Telangana (Hyderabad corridor)
      return {
        coordinates: [78.4867, 17.3850],
        pincode: pin,
        formattedAddress: address || `Telangana Area (${pin})`,
        source: 'zone_tg',
      };
    }
    if (pin.startsWith('56') || pin.startsWith('57') || pin.startsWith('58') || pin.startsWith('59')) {
      // Karnataka
      return {
        coordinates: [77.5946, 12.9716],
        pincode: pin,
        formattedAddress: address || `Karnataka Area (${pin})`,
        source: 'zone_ka',
      };
    }
    if (pin.startsWith('60') || pin.startsWith('61') || pin.startsWith('62') || pin.startsWith('63') || pin.startsWith('64')) {
      // Tamil Nadu
      return {
        coordinates: [80.2707, 13.0827],
        pincode: pin,
        formattedAddress: address || `Tamil Nadu Area (${pin})`,
        source: 'zone_tn',
      };
    }
    if (pin.startsWith('40') || pin.startsWith('41') || pin.startsWith('42') || pin.startsWith('43') || pin.startsWith('44')) {
      // Maharashtra
      return {
        coordinates: [72.8777, 19.0760],
        pincode: pin,
        formattedAddress: address || `Maharashtra Area (${pin})`,
        source: 'zone_mh',
      };
    }
    if (pin.startsWith('11')) {
      // Delhi
      return {
        coordinates: [77.2090, 28.6139],
        pincode: pin,
        formattedAddress: address || `Delhi Area (${pin})`,
        source: 'zone_dl',
      };
    }
  }

  // 4. Default safe coordinates (Bengaluru Center)
  return {
    coordinates: [77.5946, 12.9716],
    pincode: pin || '560001',
    formattedAddress: address || 'Bengaluru, Karnataka',
    source: 'default',
  };
}

/**
 * Fetch actual driving route from OSRM with turn-by-turn navigation steps
 * @param {Array<number>} originLngLat [lng, lat]
 * @param {Array<number>} destLngLat [lng, lat]
 */
async function getDrivingRoute(originLngLat, destLngLat) {
  if (!originLngLat || !destLngLat) return null;

  let [origLng, origLat] = originLngLat;
  const [destLng, destLat] = destLngLat;

  // If origin and destination are identical or within ~50m, offset origin by ~2.5km
  // so that an actual driving road route with real distance and ETA is displayed
  if (Math.abs(origLng - destLng) < 0.001 && Math.abs(origLat - destLat) < 0.001) {
    origLng = destLng + 0.022;
    origLat = destLat + 0.016;
  }

  try {
    const osrmUrl = `https://router.project-osrm.org/route/v1/driving/${origLng},${origLat};${destLng},${destLat}?overview=full&geometries=geojson&steps=true`;
    const res = await fetch(osrmUrl);
    if (!res.ok) throw new Error(`OSRM HTTP error ${res.status}`);

    const data = await res.json();
    if (data.code === 'Ok' && data.routes && data.routes.length > 0) {
      const route = data.routes[0];
      // Convert OSRM GeoJSON [lng, lat] into Leaflet [lat, lng]
      const polyline = (route.geometry?.coordinates || []).map((pt) => [pt[1], pt[0]]);
      const distanceMeters = Math.round(route.distance);
      const distanceKm = Math.round((distanceMeters / 1000) * 10) / 10;
      const durationSeconds = Math.round(route.duration);
      // City traffic multiplier (1.2x) + minimum 4 mins
      const etaMinutes = Math.max(4, Math.round((durationSeconds / 60) * 1.2));

      // Extract Turn-by-Turn Driving Steps
      const rawSteps = route.legs?.[0]?.steps || [];
      const steps = rawSteps.map((s, idx) => {
        const maneuverType = s.maneuver?.type || 'turn';
        const modifier = s.maneuver?.modifier || '';
        const street = s.name ? s.name.trim() : '';
        const distM = Math.round(s.distance);
        const distText = distM >= 1000 ? `${(distM / 1000).toFixed(1)} km` : `${distM} m`;

        let instruction = '';
        if (maneuverType === 'depart' || idx === 0) {
          instruction = street ? `Head out onto ${street}` : 'Start heading towards destination';
        } else if (maneuverType === 'arrive' || idx === rawSteps.length - 1) {
          instruction = 'Arrive at customer service location';
        } else if (modifier) {
          instruction = street
            ? `Turn ${modifier} onto ${street}`
            : `Turn ${modifier}`;
        } else {
          instruction = street ? `Continue on ${street}` : 'Continue straight along the route';
        }

        return {
          stepNumber: idx + 1,
          instruction,
          street: street || 'Road',
          distanceText: distText,
          distanceMeters: distM,
          modifier: modifier || 'straight',
          maneuverType,
        };
      });

      return {
        polyline,
        distanceMeters,
        distanceKm,
        durationSeconds,
        etaMinutes,
        steps,
        originCoordinates: [origLng, origLat],
        destinationCoordinates: [destLng, destLat],
      };
    }
  } catch (err) {
    console.warn('Driving route calculation error:', err.message);
  }

  // Straight line fallback if OSRM is unreachable
  const dLat = ((destLat - origLat) * Math.PI) / 180;
  const dLon = ((destLng - origLng) * Math.PI) / 180;
  const a =
    Math.sin(dLat / 2) * Math.sin(dLat / 2) +
    Math.cos((origLat * Math.PI) / 180) *
      Math.cos((destLat * Math.PI) / 180) *
      Math.sin(dLon / 2) *
      Math.sin(dLon / 2);
  const c = 2 * Math.atan2(Math.sqrt(a), Math.sqrt(1 - a));
  const straightDistKm = Math.max(1.5, Math.round(6371 * c * 10) / 10);

  return {
    polyline: [
      [origLat, origLng],
      [destLat, destLng],
    ],
    distanceMeters: Math.round(straightDistKm * 1000),
    distanceKm: straightDistKm,
    durationSeconds: Math.round(straightDistKm * 140),
    etaMinutes: Math.max(4, Math.round((straightDistKm / 25) * 60) + 4),
    steps: [
      {
        stepNumber: 1,
        instruction: 'Depart from provider service base',
        street: 'Provider Location',
        distanceText: '0 m',
        distanceMeters: 0,
        modifier: 'straight',
      },
      {
        stepNumber: 2,
        instruction: `Travel along direct corridor towards customer (${straightDistKm} km)`,
        street: 'Neighborhood Link Road',
        distanceText: `${straightDistKm} km`,
        distanceMeters: Math.round(straightDistKm * 1000),
        modifier: 'straight',
      },
      {
        stepNumber: 3,
        instruction: 'Arrive at customer service destination',
        street: 'Customer Address',
        distanceText: 'Destination',
        distanceMeters: 0,
        modifier: 'arrive',
      },
    ],
    originCoordinates: [origLng, origLat],
    destinationCoordinates: [destLng, destLat],
  };
}

